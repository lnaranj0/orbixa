<?php

namespace Modules\Platform\Tests\Security\Database;

use Illuminate\Auth\GenericUser;
use Illuminate\Contracts\Auth\Authenticatable;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Modules\Platform\Contracts\Tenancy\AdmissionTicket;
use Modules\Platform\Contracts\Tenancy\AdmissionVerifier;
use Modules\Platform\Contracts\Tenancy\MembershipVerifier;
use Modules\Platform\Contracts\Tenancy\OrganizationId;
use Modules\Platform\Contracts\Tenancy\TenantAccessDenied;
use Modules\Platform\Contracts\Tenancy\TenantContext;
use Modules\Platform\Contracts\Tenancy\TenantContextViolation;
use Modules\Platform\Tests\Security\SecurityTestCase;
use Modules\Platform\Tests\Security\Support\AllowListAdmissionVerifier;
use Modules\Platform\Tests\Security\Support\AllowListMembershipVerifier;

/**
 * 01-identity-tenancy, Platform contracts: authorization is checked inside
 * the transaction, and the entry points without prior membership (create
 * organization, accept invitation) roll back unless they establish one.
 */
final class TenantEntryPointsTest extends SecurityTestCase
{
    private GenericUser $actor;

    private AllowListMembershipVerifier $memberships;

    private AllowListAdmissionVerifier $admissions;

    private TenantContext $tenant;

    protected function setUp(): void
    {
        parent::setUp();

        $this->actor = new GenericUser(['id' => random_int(1, PHP_INT_MAX)]);
        $this->memberships = new AllowListMembershipVerifier;
        $this->admissions = new AllowListAdmissionVerifier;
        $this->app->instance(MembershipVerifier::class, $this->memberships);
        $this->app->instance(AdmissionVerifier::class, $this->admissions);
        $this->tenant = $this->app->make(TenantContext::class);
    }

    public function test_default_verifiers_deny_everyone(): void
    {
        $this->app->forgetInstance(MembershipVerifier::class);
        $this->app->forgetInstance(AdmissionVerifier::class);
        $this->app->forgetInstance(TenantContext::class);
        $tenant = $this->app->make(TenantContext::class);
        $organization = $this->newOrganization();

        $this->assertDenied(fn () => $tenant->runFor($this->actor, $organization, fn () => $this->fail('must not run')));
        $this->assertDenied(fn () => $tenant->runForAdmission($this->actor, $organization, AdmissionTicket::fromSecret('x'), fn () => $this->fail('must not run')));
    }

    public function test_membership_is_verified_inside_the_transaction(): void
    {
        $organization = $this->newOrganization();
        $spy = new class implements MembershipVerifier
        {
            public ?int $transactionLevel = null;

            public function hasActiveMembership(Authenticatable $actor, OrganizationId $organization): bool
            {
                $this->transactionLevel = DB::transactionLevel();

                return true;
            }
        };
        $this->app->instance(MembershipVerifier::class, $spy);
        $this->app->forgetInstance(TenantContext::class);

        $this->app->make(TenantContext::class)->runFor($this->actor, $organization, fn () => null);

        $this->assertGreaterThanOrEqual(1, $spy->transactionLevel, 'Membership must be checked inside the transaction (no TOCTOU window).');
    }

    public function test_new_organization_gets_a_server_generated_uuid_v7_and_commits_with_membership(): void
    {
        $organization = $this->tenant->runForNewOrganization($this->actor, function (OrganizationId $organization) {
            $this->insertProbe('created');
            $this->memberships->allow($this->actor, $organization); // the use case creates the owner membership

            return $organization;
        });

        $this->assertSame('7', $organization->value[14], 'Organization ids must be uuidv7 generated by the server.');
        $this->assertSame(1, $this->tenant->runFor($this->actor, $organization, fn () => $this->countProbes()));
    }

    public function test_new_organization_without_owner_membership_is_rolled_back(): void
    {
        $captured = null;

        try {
            $this->tenant->runForNewOrganization($this->actor, function (OrganizationId $organization) use (&$captured) {
                $captured = $organization;
                $this->insertProbe('orphan');
            });
            $this->fail('Expected TenantContextViolation.');
        } catch (TenantContextViolation) {
            // expected
        }

        $this->memberships->allow($this->actor, $captured);
        $this->assertSame(0, $this->tenant->runFor($this->actor, $captured, fn () => $this->countProbes()));
    }

    public function test_admission_requires_a_valid_ticket(): void
    {
        $organization = $this->newOrganization();
        $this->admissions->allow($organization, 'correct-secret');

        $this->assertDenied(fn () => $this->tenant->runForAdmission(
            $this->actor, $organization, AdmissionTicket::fromSecret('wrong-secret'), fn () => $this->fail('must not run')
        ));
    }

    public function test_admission_without_membership_is_rolled_back(): void
    {
        $organization = $this->newOrganization();
        $this->admissions->allow($organization, 'secret');

        try {
            $this->tenant->runForAdmission($this->actor, $organization, AdmissionTicket::fromSecret('secret'), fn () => $this->insertProbe('no-membership'));
            $this->fail('Expected TenantContextViolation.');
        } catch (TenantContextViolation) {
            // expected
        }

        $this->memberships->allow($this->actor, $organization);
        $this->assertSame(0, $this->tenant->runFor($this->actor, $organization, fn () => $this->countProbes()));
    }

    public function test_admission_with_membership_commits(): void
    {
        $organization = $this->newOrganization();
        $this->admissions->allow($organization, 'secret');

        $this->tenant->runForAdmission($this->actor, $organization, AdmissionTicket::fromSecret('secret'), function () use ($organization) {
            $this->insertProbe('joined');
            $this->memberships->allow($this->actor, $organization);
        });

        $this->assertSame(1, $this->tenant->runFor($this->actor, $organization, fn () => $this->countProbes()));
    }

    public function test_entry_points_cannot_be_nested_in_an_active_context(): void
    {
        $organization = $this->newOrganization();
        $this->memberships->allow($this->actor, $organization);

        $this->expectException(TenantContextViolation::class);

        $this->tenant->runFor($this->actor, $organization, fn () => $this->tenant->runForNewOrganization($this->actor, fn () => null));
    }

    private function assertDenied(\Closure $operation): void
    {
        try {
            $operation();
            $this->fail('Expected TenantAccessDenied.');
        } catch (TenantAccessDenied) {
            $this->assertNull(DB::selectOne('select platform.current_organization_id() as id')->id);
        }
    }

    private function newOrganization(): OrganizationId
    {
        return OrganizationId::fromString((string) Str::uuid());
    }

    private function insertProbe(string $label): void
    {
        DB::insert('insert into platform.tenant_probe (organization_id, label) values (platform.current_organization_id(), ?)', [$label]);
    }

    private function countProbes(): int
    {
        return (int) DB::selectOne('select count(*) as total from platform.tenant_probe')->total;
    }
}
